
import { STYLES, STYLE_NAMES } from './figure-styles/index.js'
import { wrap, err } from './wrapper.js'

function jsonToPython(obj, indent = 0) {
  const pad = ' '.repeat(indent)
  if (obj === null || obj === undefined) return 'None'
  if (typeof obj === 'boolean') return obj ? 'True' : 'False'
  if (typeof obj === 'number') return String(obj)
  if (typeof obj === 'string') return `'${obj.replace(/'/g, "\\'")}'`
  if (Array.isArray(obj)) {
    if (obj.length === 0) return '[]'
    if (obj.every(v => typeof v === 'number' || typeof v === 'string')) return `[${obj.map(v => jsonToPython(v)).join(', ')}]`
    return `[\n${obj.map(v => `${pad}  ${jsonToPython(v, indent + 2)}`).join(',\n')}\n${pad}]`
  }
  if (typeof obj === 'object') {
    const entries = Object.entries(obj)
    if (!entries.length) return '{}'
    return `{\n${entries.map(([k, v]) => `${pad}  '${k}': ${jsonToPython(v, indent + 2)}`).join(',\n')}\n${pad}}`
  }
  return String(obj)
}

function buildScript(styleName, styleConfig, data, options) {
  const { title, xlabel, ylabel, figsize, dpi } = options
  const figType = styleConfig.figure_type
  const rc = jsonToPython(styleConfig.rcParams, 0)
  const colors = jsonToPython(styleConfig.colors, 0)
  const layout = jsonToPython(styleConfig.layout, 0)

  const dataRepr = jsonToPython(data, 2)
  const figW = figsize?.[0] || 8
  const figH = figsize?.[1] || 6
  const dpiVal = dpi || 300

  let plotCode = ''
  if (figType === 'bar') plotCode = buildBarPlot(styleName, data, options)
  else if (figType === 'line') plotCode = buildLinePlot(styleName, data, options)
  else if (figType === 'scatter') plotCode = buildScatterPlot(styleName, data, options)
  else if (figType === 'radar') plotCode = buildRadarPlot(styleName, data, options)

  return `"""
Generated by dsh-research-kit MCP figure-generator
Style: ${styleName} — ${styleConfig.description}
"""
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

plt.rcParams.update(${rc})

# Style parameters
STYLE_COLORS = ${colors}
STYLE_LAYOUT = ${layout}

# User data
DATA = ${dataRepr}

# Figure setup
fig, ax = plt.subplots(figsize=(${figW}, ${figH}))

${plotCode}

# Labels
${title ? `ax.set_title('${title.replace(/'/g, "\\'")}', fontsize=12)` : '# no title'}
${xlabel ? `ax.set_xlabel('${xlabel.replace(/'/g, "\\'")}', fontsize=11)` : '# no xlabel'}
${ylabel ? `ax.set_ylabel('${ylabel.replace(/'/g, "\\'")}', fontsize=11)` : '# no ylabel'}

fig.savefig('output_${styleName}.png', dpi=${dpiVal}, facecolor='white', bbox_inches='tight')
plt.close(fig)
print('Saved output_${styleName}.png')
`
}

function buildBarPlot(styleName, data, options) {
  if (styleName === 'bar_paired_delta') {
    return `
categories = DATA.get('categories', [])
baseline = DATA.get('baseline', [])
method = DATA.get('method', [])
x = np.arange(len(categories))
bar_w = STYLE_LAYOUT['bar_width']
gap = STYLE_LAYOUT['gap']

bars_base = ax.bar(x - gap/2 - bar_w/2 + bar_w/2, baseline, width=bar_w, color=STYLE_COLORS['baseline'], label='Baseline', zorder=2)
bars_meth = ax.bar(x + gap/2 + bar_w/2 - bar_w/2 + bar_w/2, method, width=bar_w, color=STYLE_COLORS['method'], label='Method', zorder=2)

for i in range(len(categories)):
    delta = method[i] - baseline[i]
    ax.annotate(f'+{delta:.1f}%', xy=(x[i] + bar_w/2, method[i]),
                ha='center', va='bottom', fontsize=STYLE_LAYOUT.get('delta_fontsize', 9.5),
                fontweight='bold', color=STYLE_COLORS['delta'])
    ax.plot([x[i] - bar_w/2, x[i] + bar_w/2 + bar_w], [baseline[i], baseline[i]],
            color='black', linestyle='--', linewidth=0.8, zorder=1)

ax.set_xticks(x)
ax.set_xticklabels(categories)
for sp in ax.spines.values():
    sp.set_linewidth(STYLE_LAYOUT['spine_linewidth'])
ax.legend(loc='upper left')
`
  }
  return `
categories = DATA.get('categories', [])
series = DATA.get('series', {})
x = np.arange(len(categories))
n = len(series)
total_w = 0.78
bar_w = total_w / n

for i, (label, values) in enumerate(series.items()):
    offset = (i - n / 2 + 0.5) * bar_w
    color = list(STYLE_COLORS.values())[i % len(STYLE_COLORS)]
    ax.bar(x + offset, values, width=bar_w, color=color, label=label, zorder=2,
           edgecolor='white', linewidth=0.8)

ax.set_xticks(x)
ax.set_xticklabels(categories)
ax.legend(loc='upper right')
ax.grid(axis='y', color='#DDDDDD', linewidth=0.7, zorder=0)
ax.set_axisbelow(True)
`
}

function buildLinePlot(styleName, data, options) {
  if (styleName === 'line_confidence_band') {
    return `
series = DATA.get('series', {})
for name, s in series.items():
    x = np.array(s.get('x', []))
    mean = np.array(s.get('mean', []))
    std = np.array(s.get('std', []))
    color = s.get('color', list(STYLE_COLORS.values())[0])
    ax.fill_between(x, mean - std, mean + std, color=color, alpha=0.15)
    ax.plot(x, mean, color=color, linewidth=1.8, label=name)
ax.legend(framealpha=0, edgecolor='none')
for side, sp in ax.spines.items():
    sp.set_visible(side in ('left', 'bottom'))
`
  }
  if (styleName === 'line_loss_with_inset') {
    return `
series = DATA.get('series', {})
for name, s in series.items():
    x = np.array(s.get('x', []))
    y = np.array(s.get('y', []))
    ax.plot(x, y, color=s.get('color', '#1F77B4'), linewidth=1.5, label=name)
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
ax.grid(True, color='#E0E0E0', linewidth=0.6, linestyle=':', zorder=0)
ax.legend(loc='upper right', frameon=True, facecolor='white', edgecolor='#DDDDDD')
`
  }
  return `
series = DATA.get('series', {})
for name, s in series.items():
    x = np.array(s.get('x', []))
    y = np.array(s.get('y', []))
    color = s.get('color', '#5B0DAD')
    ax.plot(x, y, color=color, linewidth=1.8, label=name)
    for vline in s.get('vlines', []):
        ax.axvline(vline, color=color, lw=1.5, linestyle='--', alpha=0.85)

ref_y = DATA.get('reference_y')
if ref_y is not None:
    ax.axhline(ref_y, color=STYLE_COLORS.get('reference', '#3D78C2'), lw=1.5, linestyle='--')

for sp in ax.spines.values():
    sp.set_visible(True)
    sp.set_linewidth(1.0)
ax.tick_params(direction='out', length=4, width=0.8)
ax.legend(loc='lower right', frameon=True)
`
}

function buildScatterPlot(styleName, data, options) {
  if (styleName === 'scatter_tsne_cluster') {
    return `
clusters = DATA.get('clusters', {})
for name, c in clusters.items():
    x = np.array(c.get('x', []))
    y = np.array(c.get('y', []))
    color = c.get('color', '#6A4C93')
    ax.scatter(x, y, c=color, s=14, alpha=0.55, linewidths=0, rasterized=True, label=name)
    cx, cy = np.mean(x), np.mean(y)
    import matplotlib.colors as mcolors
    rgba = list(mcolors.to_rgba(color)); rgba[3] = 0.28
    ax.annotate(name, xy=(cx, cy), ha='center', va='center', fontsize=9,
                bbox=dict(boxstyle='round,pad=0.30', facecolor=tuple(rgba),
                          edgecolor='#2C3E50', linewidth=0.9))

for sp in ax.spines.values():
    sp.set_visible(True); sp.set_linewidth(0.9); sp.set_color('#333333')
ax.tick_params(direction='in', length=4, width=0.8)
ax.grid(True, color='#E0E0E0', linewidth=0.6, linestyle=':', zorder=0)
ax.legend(frameon=True, facecolor='white', edgecolor='#CCCCCC', markerscale=1.0)
`
  }
  return `
series = DATA.get('series', {})
for name, s in series.items():
    x = np.array(s.get('x', []))
    y = np.array(s.get('y', []))
    color = s.get('color', '#E53935')
    marker = s.get('marker', 'o')
    size = s.get('size', 30)
    ax.scatter(x, y, c=color, marker=marker, s=size, alpha=0.85, label=name,
               edgecolors='black', linewidths=0.8)
ax.legend(loc='lower right', frameon=True, facecolor='white', edgecolor='#CCCCCC')
`
}

function buildRadarPlot(styleName, data, options) {
  return `
series = DATA.get('series', {})
categories = DATA.get('categories', [])
N = len(categories)

ax.remove()
ax = fig.add_subplot(111, projection='polar')
ax.set_theta_zero_location('N')
ax.set_theta_direction(-1)
ax.set_yticks([]); ax.set_xticks([])

angles = np.linspace(0, 2*np.pi, N, endpoint=False)
def close(arr): return np.concatenate([arr, arr[:1]])

for r in [0.4, 0.55, 0.7, 0.85, 1.0]:
    ax.plot(close(angles), close(np.full(N, r)), color='#CCCCCC', lw=0.8, linestyle='--')

RMIN, RMAX = 0.35, 1.0
def nrm(v, vmin, vmax): return RMIN + (RMAX-RMIN)*(v-vmin)/(vmax-vmin)

for i, (name, s) in enumerate(series.items()):
    values = np.array(s.get('values', []))
    vmin = DATA.get('vmin', np.min(values) * 0.9)
    vmax = DATA.get('vmax', np.max(values) * 1.1)
    r = np.array([nrm(v, vmin, vmax) for v in values])
    color = s.get('color', '#76A676')
    lw = 2.8 if i == 0 else 1.3
    ax.fill(close(angles), close(r), color=color, alpha=0.18)
    ax.plot(close(angles), close(r), color=color, lw=lw, label=name)
    for j in range(N):
        ax.text(angles[j], r[j]+0.08, f'{values[j]:.2f}', ha='center', fontsize=7.8,
                color=color, bbox=dict(boxstyle='round,pad=0.12', facecolor='white',
                edgecolor='none', alpha=0.85))

ax.set_xticks(angles)
ax.set_xticklabels(categories, fontsize=9)
ax.legend(loc='upper right', bbox_to_anchor=(1.25, 1.05), frameon=False)
`
}

function generateFigure(styleName, data, options = {}) {
  if (!STYLE_NAMES.includes(styleName)) {
    return err(`未知风格 "${styleName}"。可用风格：${STYLE_NAMES.join(', ')}`)
  }
  if (!data || typeof data !== 'object') {
    return err('必须提供 data 对象（包含 categories / series / clusters 等字段）。')
  }
  const styleConfig = STYLES[styleName]
  const script = buildScript(styleName, styleConfig, data, options)
  return wrap({
    style: styleName,
    description: styleConfig.description,
    figure_type: styleConfig.figure_type,
    script,
    filename: `output_${styleName}.png`,
    instructions: '将 script 内容保存为 .py 文件并在有 matplotlib 的环境中执行，生成 PNG。如需 LaTeX 字体，请安装 texlive。',
  }, { source: 'figure-generator', confidence: 'verified' })
}

function listFigureStyles() {
  return Object.entries(STYLES).map(([name, config]) => ({
    name,
    description: config.description,
    figure_type: config.figure_type,
    colors: config.colors,
  }))
}

export { generateFigure, listFigureStyles }
